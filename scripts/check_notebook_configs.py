"""Check that the notebook still writes the committed Config_*.json files.

The configs are generated by a cell in the notebook. This runs that cell in a
temporary directory and compares what it writes with the files in the repo,
so the notebook and the JSON can't drift apart (e.g. a config edited by hand
but not in the notebook, or the other way round).

Exit code 1 if any config differs.
"""

import json
import subprocess
import sys
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
NOTEBOOK = REPO / "Abstracted Sync Matrix v2.COMBINED.2025.10.02.ipynb"


def config_cell() -> str:
    """Source of the code cell that writes the configs (found by content, not index)."""
    cells = json.loads(NOTEBOOK.read_text())["cells"]
    matches = ["".join(c["source"]) for c in cells
               if c["cell_type"] == "code" and "Config_PARTNER_Sync_Matrix.json" in "".join(c["source"])
               and "json.dumps" in "".join(c["source"])]
    if len(matches) != 1:
        sys.exit("Expected exactly one config-writing cell, found %d" % len(matches))
    return matches[0]


def main() -> int:
    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp)
        (tmp / "cell.py").write_text(config_cell())
        subprocess.run([sys.executable, "-I", "cell.py"], cwd=tmp, check=True, capture_output=True)

        written = sorted(p.name for p in tmp.glob("Config_*.json"))
        if not written:
            sys.exit("The notebook cell wrote no Config_*.json files")

        failed = False
        for name in written:
            generated = json.loads((tmp / name).read_text())
            committed_path = REPO / name
            if not committed_path.exists():
                print("FAIL %s: written by the notebook but not committed" % name)
                failed = True
                continue
            committed = json.loads(committed_path.read_text())
            if generated == committed:
                print("OK   %s" % name)
                continue
            failed = True
            keys = sorted(k for k in set(generated) | set(committed) if generated.get(k) != committed.get(k))
            print("FAIL %s differs from the notebook in: %s" % (name, ", ".join(keys)))
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
